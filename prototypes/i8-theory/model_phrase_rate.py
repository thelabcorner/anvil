print(f"    XOR leading-zero count: H={ent(lzs)[0]:.3f} b, mean {lzs.mean():.2f}")
print(f"    XOR trailing-zero count: H={ent(tzs)[0]:.3f} b, mean {tzs.mean():.2f}")
# Gorilla: 1 bit if xor==0; else 1+5 bits lz + 6 bits len + mantissa
mant = []
for x, l, t in zip(xor, lzs, tzs):
    if x == 0:
        mant.append(0)
    else:
        mb = 32 - int(l) - int(t)
        mant.append(max(mb, 0))
mant = np.array(mant)
Hmant, _ = ent(mant)
zerofrac = float((xor == 0).mean())
gor = 1.0 + (1 - zerofrac) * (1 + 5 + 6 + Hmant)
print(f"    Gorilla-style per value: zero-frac {zerofrac:.4f} -> "
      f"~{gor:.3f} b/val = {nrec*gor/8:,.0f} B for the value column")

