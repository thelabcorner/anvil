for nm, arr in (('ts (u64)', tsv), ('id (u16)', idv.astype(np.int64))):
    a_, b_, r_ = fit_ap(arr.astype(np.int64))
    Hr, kr = ent(np.rint(r_).astype(np.int64))
    Hd, kd = ent(np.diff(arr.astype(np.int64)))
    Hd2, kd2 = ent(np.diff(np.diff(arr.astype(np.int64))))
    print(f"  {nm:<10} H(resid to line)={Hr:7.3f} b/val ({kr:>6} distinct) | "
          f"H(1st diff)={Hd:6.3f} | H(2nd diff)={Hd2:6.3f}")
# value: f32 -> view as u32 and XOR (Gorilla-style)
vu = recs[:, 8:12].copy().view(np.uint32).ravel().astype(np.int64)
xor = np.bitwise_xor(vu[1:], vu[:-1])
Hx, kx = ent(xor)
print(f"  value f32  H(raw u32)={ent(vu)[0]:7.3f} | H(XOR consecutive)={Hx:7.3f} b/val ({kx} distinct)")
# leading-zero / trailing-zero structure of XOR (Gorilla cases)
def lz(x): return 32 - int(x).bit_length() if x else 32
def tz(x): return (int(x) & -int(x)).bit_length() - 1 if x else 32
lzs = np.array([lz(int(x)) for x in xor])
